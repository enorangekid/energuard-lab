serve(async (req) => {
  if (req.method === 'OPTIONS') {
    return new Response('ok', { headers: corsHeaders })
  }

  try {
    const { inquiry, store = 'korean', mode = 'simple' } = await req.json()
    const apiKey = Deno.env.get('GEMINI_API_KEY')

    if (!inquiry || inquiry.trim() === '') {
      return new Response(
        JSON.stringify({ error: '문의 내용을 입력해주세요.' }),
        { status: 400, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
      )
    }

    const systemPrompt = buildSystemPrompt(store, mode)

    const response = await fetch(
      `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${apiKey}`,
      {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          systemInstruction: {
            parts: [{ text: systemPrompt }]
          },
          contents: [
            {
              role: 'user',
              parts: [{ text: `다음 고객 문의에 답변해줘:\n\n${inquiry}` }]
            }
          ],
          generationConfig: {
            thinkingConfig: { thinkingBudget: 0 }
          }
        })
      }
    )

    const data = await response.json()

    if (data.error) {
      throw new Error(data.error.message)
    }

    const answer = data.candidates?.[0]?.content?.parts?.[0]?.text ?? '답변 생성 실패'

    return new Response(
      JSON.stringify({ answer }),
      { headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
    )
  } catch (error) {
    return new Response(
      JSON.stringify({ error: error.message }),
      { status: 400, headers: { ...corsHeaders, 'Content-Type': 'application/json' } }
    )
  }
})
